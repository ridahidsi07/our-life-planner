export function detectBrowserTimeZone(): string {
  try {
    const resolved = Intl.DateTimeFormat().resolvedOptions().timeZone;
    if (resolved && typeof resolved === 'string' && resolved.trim().length > 0) {
      return resolved.trim();
    }
  } catch {
    // Fallback below
  }
  return 'UTC';
}

